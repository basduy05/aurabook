/**
 * Chuẩn hóa chuỗi so sánh tên địa danh (bỏ tiền tố, bỏ dấu cách thừa, lowercase)
 */
export function normalizeAdminName(str: string): string {
	if (!str) return "";
	return str
		.toLowerCase()
		.replace(/^(thành phố|tỉnh|tp\.?|quận|huyện|thị xã|phường|xã|thị trấn)\s+/i, "")
		.trim();
}

/**
 * Tra cứu tỉnh theo tên hoặc mã
 */
export function findProvince(query: string): ProvinceInfo | undefined {
	const norm = normalizeAdminName(query);
	return VIETNAM_PROVINCES.find((p) => {
		const pNorm = normalizeAdminName(p.name);
		return p.code === query || pNorm === norm || p.name.toLowerCase().includes(norm);
	});
}

/**
 * Tra cứu quận/huyện theo tỉnh và tên huyện
 */
export function findDistrict(province: ProvinceInfo, query: string): DistrictInfo | undefined {
	const norm = normalizeAdminName(query);
	return province.districts.find((d) => {
		const dNorm = normalizeAdminName(d.name);
		return d.code === query || dNorm === norm || d.name.toLowerCase().includes(norm);
	});
}

/**
 * Tra cứu phường/xã theo quận/huyện và tên xã
 */
export function findWard(district: DistrictInfo, query: string): WardInfo | undefined {
	const norm = normalizeAdminName(query);
	return district.wards.find((w) => {
		const wNorm = normalizeAdminName(w.name);
		return w.code === query || wNorm === norm || w.name.toLowerCase().includes(norm);
	});
}

