function setDeep(obj, pathArr, value) {
  let curr = obj;
  for (let i = 0; i < pathArr.length - 1; i++) {
    const key = pathArr[i];
    if (!curr[key] || typeof curr[key] !== 'object') {
      curr[key] = {};
    }
    curr = curr[key];
  }
  curr[pathArr[pathArr.length - 1]] = value;
}

let updatedCount = 0;
for (const [flatKey, transValue] of Object.entries(translations)) {
  const parts = flatKey.split('.');
  setDeep(vi, parts, transValue);
  updatedCount++;
}

fs.writeFileSync(viPath, JSON.stringify(vi, null, '\t') + '\n', 'utf8');
console.log(`Successfully updated ${updatedCount} translations in messages/vi.json`);
